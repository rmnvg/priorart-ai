import type { AnalysisResult, NoveltyVerdict } from "@/types/analysis";

// A plain-Markdown brief of the analysis, written to be handed to a patent
// agent or attorney: the idea, the closest art with links, the exact searches
// already run, and what's left open. Arriving with this turns a first
// consultation from "tell me about your idea" into "here's what's been
// checked" — which is billable time an independent inventor doesn't spend.

const VERDICT_LABELS: Record<NoveltyVerdict, string> = {
  blocking: "Blocking",
  partially_overlapping: "Partially overlapping",
  not_relevant: "Not relevant",
};

const QUERY_LABELS: Record<string, string> = {
  major_markets: "Major markets",
  india_specific: "India (IN filings only)",
  broad_recall: "Broad recall",
  refined: "Refined (agent, patent terminology)",
};

function escapeCell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function buildReportBrief(result: AnalysisResult, reportUrl?: string): string {
  const pct = Math.round(result.overall_novelty_confidence * 100);
  const today = new Date().toLocaleDateString("en-CA"); // YYYY-MM-DD, local time
  const lines: string[] = [];

  lines.push("# Prior-art brief", "");
  lines.push(`_Generated by PriorArt AI on ${today}. A first-pass search, not a legal opinion._`);
  if (reportUrl) lines.push("", `Interactive report: ${reportUrl}`);
  lines.push("", "## Invention", "", result.idea_text, "");
  if (result.original_idea_text) {
    lines.push(`_Translated from the inventor's original (${result.language_name ?? "non-English"}):_`, "");
    lines.push(`> ${result.original_idea_text}`, "");
  }

  lines.push("## Summary", "");
  lines.push(`- **Novelty confidence:** ${pct}%`);
  lines.push(`- **Results reviewed:** ${result.ranked_results.length}`);
  lines.push(`- **Assessed in depth:** ${result.candidate_assessments.length}`);
  lines.push(`- **Closest matches active in India:** ${result.india_status.blocking_in_india}`);
  lines.push(
    `- **Closest matches active elsewhere, not India:** ${result.india_status.active_elsewhere_only}`
  );
  if (result.public_domain) {
    lines.push(`- **Related patents no longer in force:** ${result.public_domain.count}`);
  }
  lines.push("");

  if (result.candidate_assessments.length > 0) {
    lines.push("## Closest prior art", "");
    lines.push("| # | Document | Verdict | Overlaps | Differences |");
    lines.push("|---|---|---|---|---|");
    result.candidate_assessments.forEach((a, i) => {
      lines.push(
        `| ${i + 1} | [${escapeCell(a.title)}](${a.link}) | ${VERDICT_LABELS[a.verdict]} | ` +
          `${escapeCell(a.overlapping_elements.join("; ") || "—")} | ` +
          `${escapeCell(a.differences.join("; ") || "—")} |`
      );
    });
    lines.push("");
  }

  const discoveries = result.citation_network?.discoveries ?? [];
  if (discoveries.length > 0) {
    lines.push("## Found by citation chasing", "");
    lines.push("Referenced by the closest matches but not returned by keyword search:", "");
    for (const d of discoveries) {
      const meta = [d.assignee, d.priority_date && `priority ${d.priority_date}`]
        .filter(Boolean)
        .join(", ");
      lines.push(`- [${d.title}](${d.link})${meta ? ` — ${meta}` : ""}`);
    }
    lines.push("");
  }

  if (result.differentiation_suggestions.length > 0) {
    lines.push("## Possible differentiators", "");
    result.differentiation_suggestions.forEach((s, i) => lines.push(`${i + 1}. ${s}`));
    lines.push("");
  }

  if (result.public_domain && result.public_domain.entries.length > 0) {
    lines.push("## Related patents no longer in force", "");
    for (const e of result.public_domain.entries) {
      const why = e.reason === "term_expired" ? "20-year term expired" : "lapsed early";
      lines.push(`- [${e.title}](${e.link}) — ${why}; not active in ${e.lapsed_in.join(", ")}`);
    }
    lines.push("");
  }

  const strategy = result.search_strategy;
  if (strategy) {
    lines.push("## Searches already run", "");
    lines.push(`Core concepts: ${strategy.core_concepts.join(", ")}`);
    if (strategy.suggested_cpc) lines.push(`Suggested CPC: ${strategy.suggested_cpc}`);
    lines.push("", "| Angle | Google Patents query | Results |", "|---|---|---|");
    for (const q of strategy.queries) {
      lines.push(
        `| ${QUERY_LABELS[q.type] ?? q.type} | \`${escapeCell(q.query)}\` | ` +
          `${q.failed ? "search failed" : q.result_count} |`
      );
    }
    lines.push("");
  }

  lines.push("## Not yet covered", "");
  lines.push(
    "- Non-English-language patent literature, beyond what Google Patents machine-translates"
  );
  lines.push("- Indian Patent Office records not indexed by Google Patents (check InPASS)");
  lines.push("- Non-patent literature outside Google Scholar (standards, product manuals, theses)");
  lines.push("- Legal status verification — the statuses above are as reported by Google Patents");
  lines.push("");

  return lines.join("\n");
}

export function downloadTextFile(filename: string, contents: string, mimeType: string) {
  const url = URL.createObjectURL(new Blob([contents], { type: mimeType }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
